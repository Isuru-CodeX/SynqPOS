export function t(key: string, defaultText?: string): string {
  const lang = usePreferencesStore.getState().language ?? 'en'
  return translations[lang]?.[key] ?? translations['en']?.[key] ?? defaultText ?? key
}

export function useI18n() {
  const { language, setLanguage, currency, setCurrency } = usePreferencesStore()
  
  const translate = (key: string, defaultText?: string) => {
    return translations[language]?.[key] ?? translations['en']?.[key] ?? defaultText ?? key
  }

  return {
    t: translate,
    language,
    setLanguage,
    currency,
    setCurrency,
  }
}
